"""Reviewed archive/policy-only settings switch; callable setup plumbing, not a launcher editor.

prepare_existing reads legacy inputs and named launcher artifacts, returning a private plan.
save_existing requires its review id plus explicit stopped-writer and launcher-review attestations.
Original bytes are copied outside the checkout before receipts become common-only and settings
are saved. An interrupted switch is resumed from its validated bundle; never rolled back silently.
inspect_existing is read-only; resume_existing repeats the same approvals and refuses newer state.

Fleet-config conversion is deliberately unsupported here. No Git, discovery, authentication,
launcher execution/repair, scheduling, enrollment, automatic output capture or logging occurs.
summary() hides paths and policy values. paths() is a separate explicit local-review channel.
"""
from __future__ import annotations

import json
import os
import re
from contextlib import contextmanager
from dataclasses import dataclass, field
from pathlib import Path

from Basic._files import atomic_write_bytes
from Special._runtime.files import checked_path
from Special._settings import (SETTINGS_NAME, SettingsError, _unique_object, legacy_locations,
                               select_home, validate_document)
from Special._settings.archives import _archives, _receipt_registry
from Special._settings.migration import preview_migration
from Special._settings.store import fingerprint, write_settings

BUNDLE_ROOT = "settings-switches"
LABELS = {"cli", "app", "archives", "never_publish", "safe_values"}


def _encode(value):
    try:
        return (json.dumps(value, indent=2, ensure_ascii=True, allow_nan=False) + "\n").encode()
    except (ValueError, TypeError, RecursionError):
        raise SettingsError("settings switch record cannot be encoded") from None


def _read(path):
    path = checked_path(path)
    try:
        return path.read_bytes()
    except FileNotFoundError:
        return None
    except OSError:
        raise SettingsError("settings switch input could not be read") from None


def _revision(payload):
    return fingerprint(payload) if payload is not None else None


def _json(payload):
    try:
        return json.loads(payload.decode("utf-8"), object_pairs_hook=_unique_object)
    except (UnicodeError, ValueError, RecursionError):
        raise SettingsError("settings switch record is not unambiguous JSON") from None


def _raw_archive(payload):
    return _receipt_registry(_json(payload))[0] if payload is not None else None


def _artifact_paths(home, raw):
    """Only receipt-named files inside their root plus known profile refresh wrappers."""
    paths = []
    for record in (raw or {}).get("installations", []):
        root = Path(os.path.abspath(Path(record["root"]).expanduser()))
        if not record.get("launcher"):
            continue
        launcher = Path(record["launcher"]).expanduser()
        if not launcher.is_absolute():
            raise SettingsError("recorded launcher path is not absolute; review it separately")
        launcher = Path(os.path.abspath(launcher))
        if root not in launcher.parents:
            raise SettingsError("recorded launcher is outside its archive; review it separately")
        paths.append(launcher)
        if launcher.suffix.lower() == ".bat":
            paths.append(launcher.with_suffix(".ps1"))
    paths.extend(home / ("refresh_managed_archives" + suffix) for suffix in (".bat", ".ps1", ".sh"))
    return tuple(dict.fromkeys(paths))


def _launcher(path, payload):
    role = "refresh-all" if path.stem == "refresh_managed_archives" else "archive-launcher"
    repair = {"entry": "Elaborate/archive_manage.py" if role == "refresh-all" else "Special/archive_manager.py",
              "action": "--write-refresh-all-script" if role == "refresh-all" else "--install",
              "profile": "selected-settings-home", "runs_refresh": False}
    details = {"role": role, "format": path.suffix, "repair_plan": repair,
               "retirement_plan": "review ownership and callers, then explicitly retire only the selected launcher; keep archives/settings"}
    if payload is None:
        return {**details, "present": False, "choices": ["leave-missing", "prepare-repair"]}
    try:
        text = payload.decode("utf-8-sig")
    except UnicodeError:
        return {**details, "present": True, "readable": False, "choices": ["review-manually"]}
    normalized = text.replace("\\", "/")
    return {**details, "present": True, "readable": True,
            "generated_marker": "Generated by gitSpecOps" in text,
            "profile_selected": "--settings-home" in text,
            "manager_entry": "Special/archive_manager.py" in normalized,
            "scheduling_entry": "Elaborate/archive_manage.py" in normalized,
            "copied_remote_allowance": "--approved-remote-prefix" in text,
            "choices": ["keep-after-review", "prepare-repair", "prepare-retirement"]}


@dataclass(frozen=True)
class ExistingPlan:
    home: Path = field(repr=False)
    document: dict = field(repr=False)
    originals: dict = field(repr=False)
    artifacts: dict = field(repr=False)
    review_id: str

    def _id(self):
        return fingerprint(_encode({"home": str(self.home), "document": self.document,
            "sources": {key: _revision(value) for key, value in self.originals.items()},
            "artifacts": self.artifacts}))[:32]

    def verify(self, *, receipt_marked=False, target_saved=False):
        """Check the original approval, source/target revisions and every named artifact."""
        if self._id() != self.review_id:
            raise SettingsError("settings switch plan changed; prepare a new review")
        paths = legacy_locations(self.home)
        for label, payload in self.originals.items():
            expected = self.receipt_bytes() if label == "archives" and receipt_marked else payload
            if _read(paths[label]) != expected:
                raise SettingsError("settings switch inputs changed; no newer data was replaced")
        expected_target = _encode(self.document) if target_saved else None
        if _read(self.home / SETTINGS_NAME) != expected_target:
            raise SettingsError("settings switch target changed; no newer settings were replaced")
        for path, expected in self.artifacts.items():
            if _revision(_read(Path(path))) != expected:
                raise SettingsError("launcher artifacts changed; review them again before continuing")

    def receipt_bytes(self):
        """Mark retained archive copies as receipts; preserve all historical fields."""
        raw = _raw_archive(self.originals["archives"])
        if raw is None:
            return None
        raw["version"] = 2
        return _encode(raw)

    @property
    def bundle(self):
        return self.home / BUNDLE_ROOT / self.review_id

    def summary(self):
        choices = self.document.get("components", {}).get("archive_manage", {}).get("options", {}).get("archives", [])
        security = self.document.get("defaults", {}).get("security", {})
        return {"status": "review", "scope": "archive-and-policy", "review_id": self.review_id,
                "sources": sorted(key for key, value in self.originals.items() if value is not None),
                "archives": len(choices), "archive_modes": {mode: sum(item["mode"] == mode for item in choices)
                                                            for mode in ("update", "sync")},
                "protected_values": len(security.get("never_publish", [])),
                "allowed_values": len(security.get("safe_values", [])),
                "effects": ["preserve-original-bytes"] +
                           (["mark-existing-archive-receipts-common-only"] if self.originals["archives"] is not None else []) +
                           ["create-shared-settings"],
                "requires": ["exact-review-id", "legacy-writers-stopped", "launcher-plan-reviewed"],
                "launcher_plan": [{"artifact": number, **_launcher(Path(path), _read(Path(path)))}
                                  for number, path in enumerate(self.artifacts, 1)],
                "changes_launchers": False, "runs_repository_operations": False,
                "recovery": "inspect the saved bundle, then explicitly resume the same reviewed switch"}

    def paths(self):
        """Explicit path-only review; never policy contents, identities or remote allowances."""
        return {"settings": str(self.home / SETTINGS_NAME), "originals": str(self.bundle / "originals"),
                "archive_receipts": str(legacy_locations(self.home)["archives"]),
                "artifacts": [{"artifact": number, "path": path} for number, path in enumerate(self.artifacts, 1)]}


def prepare_existing(home=None):
    """Read and validate the narrow existing-settings switch; creates nothing."""
    selected, _ = select_home(home, component="archive_manage")
    checked_path(selected / SETTINGS_NAME)
    if "GITSPECOPS_SYNC_HOME" in os.environ:
        raise SettingsError("this archive/policy switch does not handle an alternate fleet directory")
    paths = legacy_locations(selected)
    originals = {label: _read(path) for label, path in paths.items()}
    if any(originals[key] is not None for key in ("cli", "app")):
        raise SettingsError("fleet settings need a separately reviewed switch; this action handles archives and policy only")
    preview = preview_migration(selected)
    preview.verify()
    if any(_revision(payload) != preview.snapshots[paths[key]] for key, payload in originals.items()):
        raise SettingsError("settings inputs changed during review")
    choices = preview.document.get("components", {}).get("archive_manage", {}).get("options", {}).get("archives", [])
    _archives(choices)
    raw = _raw_archive(originals["archives"])
    artifacts = {str(path): _revision(_read(path)) for path in _artifact_paths(selected, raw)}
    plan = ExistingPlan(selected, preview.document, originals, artifacts, "")
    object.__setattr__(plan, "review_id", plan._id())
    plan.receipt_bytes()  # Refuse unencodable receipt metadata before any bundle/state write.
    plan.verify()
    return plan


@contextmanager
def _locked(home):
    """Serialize switches and cooperating archive writers; never reclaim a stale lock."""
    owned = []
    try:
        if _read(home / ".settings.lock") is not None:
            raise SettingsError("settings writer is busy; no switch was started")
        for name in (".settings-switch.lock", ".archive-registry.lock"):
            path = checked_path(home / name)
            descriptor = os.open(path, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
            owned.append(path)
            os.close(descriptor)
        yield
    except FileExistsError:
        raise SettingsError("settings/archive writer is busy; no lock was reclaimed") from None
    finally:
        failed = False
        for path in reversed(owned):
            try:
                path.unlink()
            except OSError:
                failed = True
        if failed:
            raise SettingsError("switch lock cleanup failed; inspect saved state before retrying") from None


def _exclusive(path, payload):
    path = checked_path(path)
    path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    descriptor = os.open(path, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
    with os.fdopen(descriptor, "wb") as handle:
        handle.write(payload)
        handle.flush()
        os.fsync(handle.fileno())


def _approve(plan, approve, writers_stopped, launchers_reviewed):
    if not isinstance(approve, str) or approve != plan.review_id:
        raise SettingsError("use the exact review id from the existing-settings plan")
    if writers_stopped is not True or launchers_reviewed is not True:
        raise SettingsError("confirm legacy writers are stopped and the separate launcher plan was reviewed")


def _finish(plan):
    current = _read(legacy_locations(plan.home)["archives"])
    marked = plan.receipt_bytes()
    if marked is not None and current == plan.originals["archives"]:
        plan.verify()
        atomic_write_bytes(legacy_locations(plan.home)["archives"], marked)
    plan.verify(receipt_marked=marked is not None)
    write_settings(plan.document, home=plan.home, expected_revision=None,
                   check_sources=lambda: plan.verify(receipt_marked=marked is not None))
    plan.verify(receipt_marked=marked is not None, target_saved=True)
    return {"status": "saved", "review_id": plan.review_id, "originals_retained": True,
            "changes_launchers": False, "runs_repository_operations": False}


def save_existing(plan, approve, *, writers_stopped=False, launchers_reviewed=False):
    """Explicitly preserve originals and activate only this reviewed archive/policy profile.

    Cooperating settings/archive locks and byte checks are not an OS-wide transaction. Stop
    independent legacy writers first. Any partial state retains the bundle for inspect/resume.
    No automatic rollback, file deletion, launcher change or old-version upgrade is attempted.
    """
    _approve(plan, approve, writers_stopped, launchers_reviewed)
    plan.verify()
    try:
        with _locked(plan.home):
            plan.verify()
            checked_path(plan.bundle).mkdir(mode=0o700, parents=True, exist_ok=False)
            destinations = legacy_locations(plan.bundle / "originals")
            for label, payload in plan.originals.items():
                if payload is not None:
                    _exclusive(destinations[label], payload)
            _exclusive(plan.bundle / "candidate.json", _encode(plan.document))
            _exclusive(plan.bundle / "manifest.json", _encode({"version": 1, "review_id": plan.review_id,
                "sources": {key: _revision(value) for key, value in plan.originals.items()}, "artifacts": plan.artifacts}))
            plan.verify()
            return _finish(plan)
    except (OSError, ValueError):
        raise SettingsError("settings switch did not finish cleanly; inspect its retained bundle before any resume") from None


def _bundle_plan(home, review_id):
    """Load only a validated, approval-bound bundle; never treat backups as active settings."""
    selected, _ = select_home(home, component="archive_manage")
    if not isinstance(review_id, str) or re.fullmatch(r"[0-9a-f]{32}", review_id) is None:
        raise SettingsError("invalid settings switch review id")
    bundle = checked_path(selected / BUNDLE_ROOT / review_id)
    manifest_bytes, candidate_bytes = _read(bundle / "manifest.json"), _read(bundle / "candidate.json")
    if manifest_bytes is None or candidate_bytes is None:
        raise SettingsError("settings switch bundle is incomplete; do not change live state automatically")
    manifest = _json(manifest_bytes)
    if (not isinstance(manifest, dict) or set(manifest) != {"version", "review_id", "sources", "artifacts"}
            or type(manifest["version"]) is not int or manifest["version"] != 1
            or manifest["review_id"] != review_id or not isinstance(manifest["sources"], dict)
            or set(manifest["sources"]) != LABELS or not isinstance(manifest["artifacts"], dict)):
        raise SettingsError("settings switch manifest is invalid")
    originals = {label: _read(path) for label, path in legacy_locations(bundle / "originals").items()}
    if any(_revision(value) != manifest["sources"][key] for key, value in originals.items()):
        raise SettingsError("preserved originals changed; automatic resume is refused")
    preview = preview_migration(bundle / "originals")
    preview.verify()
    document = validate_document(_json(candidate_bytes))
    if any(originals[key] is not None for key in ("cli", "app")) or document != preview.document:
        raise SettingsError("switch candidate differs from the preserved archive/policy inputs")
    paths = _artifact_paths(selected, _raw_archive(originals["archives"]))
    if set(map(str, paths)) != set(manifest["artifacts"]):
        raise SettingsError("settings switch artifact inventory changed")
    plan = ExistingPlan(selected, document, originals, manifest["artifacts"], review_id)
    if plan._id() != review_id:
        raise SettingsError("settings switch bundle no longer matches its approval")
    return plan


def inspect_existing(home, review_id):
    """Read-only recovery status, distinguishing complete, resumable and conflicting state."""
    plan = _bundle_plan(home, review_id)
    target = _read(plan.home / SETTINGS_NAME)
    current = _read(legacy_locations(plan.home)["archives"])
    marked = plan.receipt_bytes()
    try:
        if target is not None:
            plan.verify(receipt_marked=marked is not None, target_saved=True)
            return {"status": "saved", "review_id": review_id, "can_resume": False}
        if current not in (plan.originals["archives"], marked):
            raise SettingsError("receipt state changed")
        plan.verify(receipt_marked=marked is not None and current == marked)
    except ValueError:
        return {"status": "needs-review", "review_id": review_id, "can_resume": False}
    return {"status": "interrupted", "review_id": review_id, "can_resume": True,
            "receipt_only": marked is not None and current == marked}


def resume_existing(home, review_id, *, writers_stopped=False, launchers_reviewed=False):
    """Explicitly finish the approved switch; never overwrite newer state or restore old authority."""
    plan = _bundle_plan(home, review_id)
    _approve(plan, review_id, writers_stopped, launchers_reviewed)
    try:
        with _locked(plan.home):
            status = inspect_existing(home, review_id)
            if status["status"] == "saved":
                return {**status, "status": "unchanged", "originals_retained": True}
            if not status["can_resume"]:
                raise SettingsError("settings switch needs fresh review; no newer data was replaced")
            return _finish(plan)
    except (OSError, ValueError):
        raise SettingsError("settings switch resume did not finish cleanly; inspect retained state") from None
