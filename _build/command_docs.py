"""Write docs/COMMANDS.md from each command's own header, so the reference cannot drift.

Why:          the header at the top of every command's file is its documentation (`gitso docs`
              prints it). This puts the same text in one page GitHub shows, by layer.
Reads:        gitso.py's command list and each command file's header (parsed, never imported).
May change:   docs/COMMANDS.md, only when run with --write.
Results:      the page on stdout, or the file; tests/repo/test_command_docs.py fails when the
              file differs from what this would write.
Layer:        setup (_build).
Status:       working

    python _build/command_docs.py            # print the page
    python _build/command_docs.py --write    # update docs/COMMANDS.md
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import gitso  # noqa: E402

TARGET = ROOT / "docs" / "COMMANDS.md"


def render() -> str:
    lines = ["# Commands", "",
             "<!-- Generated by _build/command_docs.py from each command's header. Do not edit by",
             "     hand: change the header, then run `python _build/command_docs.py --write`. -->", "",
             "Every command runs as `gitso <command>` (or `python gitso.py <command>`), and by its own",
             "path. `gitso docs <command>` prints the same text in a terminal.", ""]
    layers: dict[str, list] = {}
    for command in gitso.COMMANDS:
        layers.setdefault(command.script.split("/")[0], []).append(command)
    for layer, commands in layers.items():
        lines.append(f"- **{gitso.LAYERS.get(layer, layer)}:** "
                     + ", ".join(f"[{c.name}](#{c.name})" for c in commands))
    for layer, commands in layers.items():
        lines += ["", f"## {gitso.LAYERS.get(layer, layer)}"]
        for command in commands:
            lines += ["", f"### {command.name}", "", f"`gitso {command.name}`, or `{command.script}`.", "",
                      "```text", command.documentation().rstrip(), "```"]
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    page = render()
    if argv == ["--write"]:
        TARGET.write_text(page, encoding="utf-8", newline="\n")
        print(f"wrote {TARGET.relative_to(ROOT)}")
        return 0
    if argv:
        print(__doc__)
        return 2
    sys.stdout.reconfigure(errors="replace")
    print(page, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
