"""Write docs/COMMANDS.md from each command's own header, so the reference cannot drift.

Why:          the header at the top of every command's file is its documentation (`gitso docs`
              prints it). This puts the same text in one page GitHub shows, by layer.
Reads:        gitso.py's command list and each command file's header (parsed, never imported).
May change:   docs/COMMANDS.md, only when run with --write.
Results:      the page on stdout, or the file; tests/repo/test_command_docs.py fails when the
              file differs from what this would write.
Layer:        setup (_build).
Status:       working

    python _build/command_docs.py            # print the page
    python _build/command_docs.py --write    # update docs/COMMANDS.md
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import gitso  # noqa: E402

TARGET = ROOT / "docs" / "COMMANDS.md"


def _anchor(text: str) -> str:
    """GitHub's heading anchor: lower case, spaces to hyphens, most punctuation dropped."""
    return "".join(c for c in text.lower().replace(" ", "-") if c.isalnum() or c in "-_")


def _title(group) -> str:
    first = group[0].name
    if len(group) == 1:
        return first
    subject = first.split(" ")[0]
    return f"{subject} " + " / ".join(c.name.split(" ", 1)[1] for c in group)


def render() -> str:
    lines = ["# Commands", "",
             "<!-- Generated by _build/command_docs.py from each command's header. Do not edit by",
             "     hand: change the header, then run `python _build/command_docs.py --write`. -->", "",
             "Every command runs as `gitso <command>` (or `python gitso.py <command>`), and by its own",
             "path. A subject's actions share a section (`archive add`, `archive remove`, ...); `gitso",
             "<subject>` lists them. `gitso docs <command>` prints the same text in a terminal.", ""]
    layers: dict[str, list] = {}
    for command in gitso.COMMANDS:
        layers.setdefault(command.script.split("/")[0], []).append(command)
    sections: dict[str, list] = {}
    for layer, commands in layers.items():
        groups: list = []
        for command in commands:  # actions of one subject that share a file share a section
            if groups and groups[-1][0].script == command.script:
                groups[-1].append(command)
            else:
                groups.append([command])
        sections[layer] = groups
    for layer, groups in sections.items():
        lines.append(f"- **{gitso.LAYERS.get(layer, layer)}:** "
                     + ", ".join(f"[{c.name}](#{_anchor(_title(group))})" for group in groups for c in group))
    for layer, groups in sections.items():
        lines += ["", f"## {gitso.LAYERS.get(layer, layer)}"]
        for group in groups:
            typed = ", ".join(f"`gitso {c.name}`" for c in group)
            lines += ["", f"### {_title(group)}", "", f"{typed}; or `{group[0].script}`.", ""]
            if len(group) > 1:
                lines += [f"- `{c.name}`: {c.description()}" for c in group] + [""]
            lines += ["```text", group[0].documentation().rstrip(), "```"]
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    page = render()
    if argv == ["--write"]:
        TARGET.write_text(page, encoding="utf-8", newline="\n")
        print(f"wrote {TARGET.relative_to(ROOT)}")
        return 0
    if argv:
        print(__doc__)
        return 2
    sys.stdout.reconfigure(errors="replace")
    print(page, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
